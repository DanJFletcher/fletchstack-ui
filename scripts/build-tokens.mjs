import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { compileTokens, cssName, flattenTokens } from './token-compiler.mjs';

/**
 * Load an authoritative JSON token document.
 **/
async function readTokens(file) {
  return JSON.parse(await readFile(new URL(`../tokens/${file}`, import.meta.url), 'utf8'));
}

/**
 * Render complete semantic declarations for a theme boundary.
 **/
function renderScope(name, values) {
  const selector = name === 'corporate' ? ':root, [data-theme="corporate"]' : `[data-theme="${name}"]`;
  return `${selector} {\n${Object.entries(values).map(([key, value]) => `  ${key}: ${value};`).join('\n')}\n}`;
}

/**
 * Require identical semantic names and types across all themes.
 **/
function contractOf(document) {
  return Object.entries(flattenTokens(document.semantic)).map(([path, token]) => `${path}:${token.$type}`).sort().join('\n');
}

const primitives = await readTokens('primitives.json');
const files = (await readdir(new URL('../tokens', import.meta.url))).filter(file => file.endsWith('.json') && file !== 'primitives.json').sort();
const corporate = await readTokens('corporate.json');
const scopes = [];
for (const file of files) {
  const theme = await readTokens(file);
  if (contractOf(theme) !== contractOf(corporate)) throw new Error(`Semantic contract mismatch: ${file}`);
  const name = file.replace('.json', '');
  if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`Invalid theme identifier: ${name}`);
  scopes.push(renderScope(name, compileTokens({ ...primitives, ...theme })));
}
await mkdir(new URL('../src/generated', import.meta.url), { recursive: true });
await writeFile(new URL('../src/generated/tokens.css', import.meta.url), `/* Generated by npm run tokens. Do not edit. */\n${scopes.join('\n\n')}\n`);
const rows = Object.entries(flattenTokens(corporate.semantic)).map(([path, token]) => `| \`${cssName(path)}\` | ${token.$description} | ${token.$type} |`);
await writeFile(new URL('../docs/tokens.md', import.meta.url), `# Public semantic tokens\n\nGenerated from the Corporate contract; every theme supplies every property. Values resolve from primitives at build time and are redeclared at each theme boundary.\n\n| CSS property | Purpose | DTCG type |\n| --- | --- | --- |\n${rows.join('\n')}\n\nOverride these properties on a containing element or on Button via style/className. Load override styles after the library. A nested explicit theme resets the contract. Do not use internal primitive names.\n`);
console.log(`Generated ${files.length} themes with ${rows.length} semantic properties each.`);
