import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { compileTokens, cssName, flattenTokens } from './token-compiler.mjs';

/**
 * Load an authoritative JSON token document.
 **/
async function readTokens(root, file) {
  return JSON.parse(await readFile(new URL(`tokens/${file}`, root), 'utf8'));
}

/**
 * Render complete theme declarations, defaulting only roots without a theme.
 **/
function renderScope(name, values) {
  const selector =
    name === 'corporate'
      ? ':root:not([data-theme]), [data-theme="corporate"]'
      : `[data-theme="${name}"]`;
  const declarations = Object.entries(values)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n');

  return `${selector} {\n${declarations}\n}`;
}

/**
 * Require identical semantic names and types across all themes.
 **/
function contractOf(document) {
  return Object.entries(flattenTokens(document.semantic))
    .map(([path, token]) => `${path}:${token.$type}`)
    .sort()
    .join('\n');
}

/**
 * Compile discovered themes after checking their semantic contract and identifiers.
 **/
async function compileThemes(root, files, primitives, corporate) {
  const scopes = [];
  for (const file of files) {
    const theme = await readTokens(root, file);
    if (contractOf(theme) !== contractOf(corporate)) {
      throw new Error(`Semantic contract mismatch: ${file}`);
    }
    const name = file.replace('.json', '');
    if (!/^[a-z][a-z0-9-]*$/.test(name)) {
      throw new Error(`Invalid theme identifier: ${name}`);
    }
    scopes.push(renderScope(name, compileTokens({ ...primitives, ...theme })));
  }

  return scopes;
}

/**
 * Publish the semantic reference with spatial guidance and return its property count.
 **/
async function writeReference(root, corporate) {
  const rows = Object.entries(flattenTokens(corporate.semantic)).map(
    ([path, token]) => `| \`${cssName(path)}\` | ${token.$description} | ${token.$type} |`,
  );
  await writeFile(
    new URL('docs/tokens.md', root),
    `# Public semantic tokens\n\nGenerated from the Corporate contract; every theme supplies every property. Values resolve from primitives at build time and are redeclared at each theme boundary.\n\n| CSS property | Purpose | DTCG type |\n| --- | --- | --- |\n${rows.join('\n')}\n\nOverride these properties on a containing element or on Button via style/className. Load override styles after the library. A nested explicit theme resets the contract. Do not use internal primitive names.\n\nChoose a role by its purpose rather than its current value. See the [Spatial system](spatial-system.md) for spacing, sizing, layout ownership, and compatibility guidance. See [Motion](motion.md) for timing, easing, preferences, and customization.\n`,
  );

  return rows.length;
}

/**
 * Build theme CSS and its reference in a project directory URL using real file I/O.
 * Invalid token documents or mismatched themes reject before outputs are written.
 **/
export async function buildTokens(root) {
  const primitives = await readTokens(root, 'primitives.json');
  const files = (await readdir(new URL('tokens', root)))
    .filter((file) => file.endsWith('.json') && file !== 'primitives.json')
    .sort();
  const corporate = await readTokens(root, 'corporate.json');
  const scopes = await compileThemes(root, files, primitives, corporate);

  await mkdir(new URL('src/generated', root), { recursive: true });
  await writeFile(
    new URL('src/generated/tokens.css', root),
    `/* Generated by npm run tokens. Do not edit. */\n${scopes.join('\n\n')}\n`,
  );

  const count = await writeReference(root, corporate);

  console.log(`Generated ${files.length} themes with ${count} semantic properties each.`);
}
