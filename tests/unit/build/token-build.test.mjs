import { afterEach, beforeEach, expect, it, vi } from 'vitest';

const files = vi.hoisted(() => ({ readFile: vi.fn(), readdir: vi.fn(), mkdir: vi.fn(), writeFile: vi.fn() }));
vi.mock('node:fs/promises', () => files);

beforeEach(() => {
  vi.resetModules();
  vi.resetAllMocks();
  vi.spyOn(console, 'log').mockImplementation(() => {});
});
afterEach(() => { vi.restoreAllMocks(); });

/**
 * Supply fresh token documents at the filesystem boundary without touching disk.
 **/
function provideTokens(overrides = {}, names = ['primitives.json', 'luna.json', 'corporate.json', 'README.md']) {
  const documents = {
    'primitives.json': { primitive: { small: { $type: 'number', $value: 2 }, large: { $type: 'number', $value: 4 } } },
    'corporate.json': { semantic: { count: { $type: 'number', $value: '{primitive.small}', $description: 'Item count.' } } },
    'luna.json': { semantic: { count: { $type: 'number', $value: '{primitive.large}', $description: 'Item count.' } } },
    ...overrides,
  };
  files.readdir.mockResolvedValue(names);
  files.readFile.mockImplementation(async file => JSON.stringify(documents[new URL(file).pathname.split('/').at(-1)]));
  files.mkdir.mockResolvedValue(undefined);
  files.writeFile.mockResolvedValue(undefined);
}

/**
 * Return the content written to a named output through the mocked filesystem.
 **/
function outputAt(suffix) {
  return files.writeFile.mock.calls.find(([file]) => new URL(file).pathname.endsWith(suffix))?.[1];
}

it('writes complete semantic CSS for the discovered themes in stable order', async () => {
  // arrange
  provideTokens();
  const expected = '/* Generated by npm run tokens. Do not edit. */\n:root:not([data-theme]), [data-theme="corporate"] {\n  --fs-count: 2;\n}\n\n[data-theme="luna"] {\n  --fs-count: 4;\n}\n';

  // act
  await import('../../../scripts/build-tokens.mjs');

  // assert
  expect(outputAt('/src/generated/tokens.css')).toBe(expected);
});

it('writes the public token reference from semantic descriptions', async () => {
  // arrange
  provideTokens();
  const expected = '| `--fs-count` | Item count. | number |';

  // act
  await import('../../../scripts/build-tokens.mjs');

  // assert
  expect(outputAt('/docs/tokens.md')).toContain(expected);
});

it('creates the generated stylesheet directory for a fresh checkout', async () => {
  // arrange
  provideTokens();
  const expected = new URL('../../../src/generated', import.meta.url);

  // act
  await import('../../../scripts/build-tokens.mjs');

  // assert
  expect(files.mkdir).toHaveBeenCalledWith(expected, { recursive: true });
});

it.each([
  { name: 'a missing semantic property', theme: { semantic: {} } },
  { name: 'a different semantic type', theme: { semantic: { count: { $type: 'fontWeight', $value: '{primitive.large}', $description: 'Count.' } } } },
  { name: 'an extra semantic property', theme: { semantic: { count: { $type: 'number', $value: '{primitive.large}', $description: 'Count.' }, extra: { $type: 'number', $value: '{primitive.large}', $description: 'Extra.' } } } },
])('rejects a theme with $name before writing outputs', async ({ theme }) => {
  // arrange
  provideTokens({ 'luna.json': theme });

  // act
  const result = import('../../../scripts/build-tokens.mjs');

  // assert
  await expect(result).rejects.toThrow('Semantic contract mismatch: luna.json');
  expect(files.writeFile).not.toHaveBeenCalled();
});

it('rejects filenames that are not valid theme identifiers', async () => {
  // arrange
  const theme = { semantic: { count: { $type: 'number', $value: '{primitive.small}', $description: 'Count.' } } };
  provideTokens({ 'Brand.json': theme }, ['primitives.json', 'corporate.json', 'Brand.json']);

  // act
  const result = import('../../../scripts/build-tokens.mjs');

  // assert
  await expect(result).rejects.toThrow('Invalid theme identifier: Brand');
});

it('surfaces token-file read errors', async () => {
  // arrange
  provideTokens();
  const expected = new Error('Token file unavailable');
  files.readFile.mockRejectedValue(expected);

  // act
  const result = import('../../../scripts/build-tokens.mjs');

  // assert
  await expect(result).rejects.toBe(expected);
});

it('surfaces output write errors', async () => {
  // arrange
  provideTokens();
  const expected = new Error('Output directory is read-only');
  files.writeFile.mockRejectedValue(expected);

  // act
  const result = import('../../../scripts/build-tokens.mjs');

  // assert
  await expect(result).rejects.toBe(expected);
});

it('links the spatial guide from the generated public reference', async () => {
  // arrange
  provideTokens();
  const expected = '[Spatial system](spatial-system.md)';

  // act
  await import('../../../scripts/build-tokens.mjs');

  // assert
  expect(outputAt('/docs/tokens.md')).toContain(expected);
});
